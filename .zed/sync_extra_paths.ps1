# Re-imports python.analysis.extraPaths from .vscode/settings.json (the file
# your build regenerates, driven by repo.toml "vscode.python_env.PYTHONPATH")
# into a generated, gitignored ty.toml at the repo root ([environment] table),
# prefixed with the committed shared config in ty.base.toml (rules).
# ty discovers ty.toml on its own (VS Code and Zed alike), so no editor
# settings file needs to contain machine/build-specific paths or ty rules.
#
# Idempotent: rewrites ty.toml only when its content changed.
# Runs from the Zed task "sync vscode python extraPaths".

$ErrorActionPreference = "Stop"

$repoRoot = Split-Path -Parent $PSScriptRoot
$vscodeSettings = Join-Path $repoRoot ".vscode\settings.json"
$tyToml = Join-Path $repoRoot "ty.toml"
$tyBase = Join-Path $repoRoot "ty.base.toml"
$pythonVersion = "3.12"

if (-not (Test-Path $vscodeSettings)) {
    throw "Missing $vscodeSettings - run the build once to generate it."
}

# 1) Extract the new path list from the build-generated .vscode settings.
#    That file is written leniently by VS Code tooling (comments, trailing and
#    doubled commas), so extract only the extraPaths array via regex instead
#    of parsing the whole file as JSON.
#    ReadAllText defaults to UTF-8 (BOM-aware) - avoids cp1252 mojibake on UTF-8 text.
$raw = [System.IO.File]::ReadAllText($vscodeSettings)
if ($raw -match '"python\.analysis\.extraPaths"\s*:\s*\[([^\]]*)\]') {
    $new = @([regex]::Matches($Matches[1], '"([^"]*)"') |
        ForEach-Object { $_.Groups[1].Value } | Where-Object { $_ -ne "" })
}
else {
    throw "python.analysis.extraPaths not found in $vscodeSettings - build output format changed?"
}

# ty anchors each checked file's canonical (real) path to a search-root to
# derive its package for relative imports. repo_build materializes localized
# copies of the repo-local exts under _build (real directories on Windows, not
# symlinks), so a source file is NOT under the build search root, ty fails to
# infer its package, and relative imports like `from .utils.api_utils import ...`
# error out (absolute imports still resolve). Map exts paths to their real
# source directories when one exists; everything else stays untouched.
#
# Exception: premake/pybind11 extensions whose localized build tree contains a
# python package (an __init__.py somewhere) in a top-level directory the source
# tree has no equivalent of - the import package is composed only into the
# build tree, which also carries the built .pyd and .pyi stubs
# (e.g. eca.swpdm.openswx -> eca/swpdm/openswx). Keep BOTH entries for those:
# the source root anchors relative imports of files under source/extensions,
# and the build root is the only path from which ty can resolve the dotted
# module name itself.
$new = @(
    $new | ForEach-Object {
        if ($_ -match '^_build/windows-x86_64/(release|debug)/exts/(.+)$') {
            $extName = $Matches[2]
            $sourceDir = Join-Path $repoRoot ("source/extensions/" + $extName)
            if (-not (Test-Path $sourceDir)) { return $_ }
            $buildDir = Join-Path $repoRoot $_
            if (-not (Test-Path $buildDir)) { return "source/extensions/$extName" }
            # Top-level dirs present in the localized build tree but missing from source.
            $addsPackage = $false
            # Bounded-depth package probe. Prebundled wheel dirs inside build trees can
            # be unreadable, so ignore access errors instead of failing the whole sync.
            foreach ($dir in @(Get-ChildItem $buildDir -Force -Directory)) {
                if (Test-Path (Join-Path $sourceDir $dir.Name)) { continue }
                if (Get-ChildItem -LiteralPath $dir.FullName -Recurse -Filter "__init__.py" -Depth 6 -ErrorAction SilentlyContinue |
                        Select-Object -First 1) {
                    $addsPackage = $true
                    break
                }
            }
            if ($addsPackage) {
                "source/extensions/$extName"; $_
            }
            else {
                "source/extensions/$extName"
            }
        }
        else { $_ }
    }
)

# ty refuses to start if any extra-path is missing, and the vscode list can
# reference dirs a given build never produced - keep only existing ones.
$new = @($new | Where-Object { Test-Path (Join-Path $repoRoot $_) -PathType Container })

# 2) Render ty.toml. TOML literal strings ('...') need no escaping for these paths.
$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("# GENERATED by .zed/sync_extra_paths.ps1 from ty.base.toml + .vscode/settings.json - do not edit, do not commit.")
$lines.Add("# Edit shared settings (rules) in ty.base.toml instead.")
$lines.Add("")
if (Test-Path $tyBase) {
    $lines.Add([System.IO.File]::ReadAllText($tyBase).Replace("`r`n", "`n").TrimEnd())
    $lines.Add("")
}
$lines.Add("[environment]")
$lines.Add("python-version = '$pythonVersion'")
$lines.Add("extra-paths = [")
foreach ($path in $new) { $lines.Add("    '$path',") }
$lines.Add("]")
$out = ($lines -join "`n") + "`n"

# 3) Only rewrite when the content actually changed (idempotent).
if ((Test-Path $tyToml) -and ([System.IO.File]::ReadAllText($tyToml) -eq $out)) {
    Write-Host "OK: ty.toml already matches .vscode/settings.json ($($new.Count) paths)"
    exit 0
}

$enc = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($tyToml, $out, $enc)
Write-Host ("OK: wrote {0} extra-paths from .vscode/settings.json into ty.toml" -f $new.Count)
